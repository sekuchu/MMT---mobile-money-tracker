const TABLES: Record<"sr" | "en", Record<TranslationKey, string>> = { en, sr };

export function t(
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const template = TABLES[getLang()][key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

/** Serbian needs 1 / 2–4 / 5+ forms; English only distinguishes singular. */
export function countText(count: number): string {
  if (getLang() === "en") {
    return t(count === 1 ? "activity.countOne" : "activity.countFew", { count });
  }
  const mod10 = count % 10;
  const mod100 = count % 100;
  const key =
    mod10 === 1 && mod100 !== 11
      ? "activity.countOne"
      : mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)
        ? "activity.countFew"
        : "activity.countMany";
  return t(key, { count });
}
