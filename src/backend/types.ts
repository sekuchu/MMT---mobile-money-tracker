export type Category =
  | "food"
  | "groceries"
  | "transport"
  | "entertainment"
  | "shopping"
  | "bills"
  | "other";

export type TxnType = "income" | "expense";

export interface CategoryOption {
  id: Category;
  label: string;
}

export const CATEGORIES: CategoryOption[] = [
  { id: "food", label: "Food" },
  { id: "groceries", label: "Groceries" },
  { id: "transport", label: "Transport" },
  { id: "entertainment", label: "Entertainment" },
  { id: "shopping", label: "Shopping" },
  { id: "bills", label: "Bills" },
  { id: "other", label: "Other" },
];

export const CATEGORY_LABELS: Record<Category, string> = CATEGORIES.reduce(
  (acc, c) => {
    acc[c.id] = c.label;
    return acc;
  },
  {} as Record<Category, string>,
);

export interface TxnInput {
  amount: number;
  type: TxnType;
  description: string;
  category: Category | null;
  /** Local calendar date, yyyy-mm-dd. */
  date: string;
  notes: string;
}

export interface Txn extends TxnInput {
  id: string;
  createdBy: string;
  createdAt: number | null;
  updatedAt: number | null;
  /** True while the write is still queued locally (offline / not yet acknowledged). */
  pending: boolean;
}

export interface Wallet {
  id: string;
  name: string;
  currency: string;
  initialBalance: number;
  members: string[];
  memberNames: Record<string, string>;
  inviteCode: string;
}

export interface WalletPatch {
  name?: string;
  currency?: string;
  initialBalance?: number;
}

export interface AccountUser {
  uid: string;
  email: string | null;
  name: string;
}

export type Unsub = () => void;

export interface AuthApi {
  subscribe(
    cb: (user: AccountUser | null) => void,
    onError?: (error: Error) => void,
  ): Unsub;
  signUp(email: string, password: string, name: string): Promise<void>;
  signIn(email: string, password: string): Promise<void>;
  signOut(): Promise<void>;
}

export interface Backend {
  kind: "firebase" | "demo";
  auth: AuthApi;
  createWallet(
    user: AccountUser,
    input: { name: string; currency: string; initialBalance: number },
  ): Promise<string>;
  joinWallet(user: AccountUser, code: string): Promise<string>;
  subscribeMembership(
    uid: string,
    cb: (walletId: string | null) => void,
    onError?: (error: Error) => void,
  ): Unsub;
  subscribeWallet(
    walletId: string,
    cb: (wallet: Wallet) => void,
    onError?: (error: Error) => void,
  ): Unsub;
  subscribeTransactions(
    walletId: string,
    cb: (transactions: Txn[]) => void,
    onError?: (error: Error) => void,
  ): Unsub;
  updateWallet(walletId: string, patch: WalletPatch): Promise<void>;
  /** `id` is generated by the caller so retries cannot duplicate a transaction. */
  saveTransaction(
    walletId: string,
    input: TxnInput,
    id: string,
  ): Promise<void>;
  updateTransaction(
    walletId: string,
    id: string,
    input: TxnInput,
  ): Promise<void>;
  deleteTransaction(walletId: string, id: string): Promise<void>;
}
